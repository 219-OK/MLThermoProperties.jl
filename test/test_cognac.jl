                # Activity coefficients. The network runs in Float32, so agreement with the
                # reference implementation is bounded by its roundoff, not by the equations.
                lnγ = log.(activity_coefficient(model, 1e5, data.T, data.x))
                @test all(isapprox.(lnγ, data.lnγ; rtol = 1e-5, atol = 1e-5))

                n == 1 || continue
                # Ψ_kk = 1 at every temperature, and lnγ → 0 for every pure component
