            for (n, (system, data)) in enumerate(systems)
                model = Model(system; userlocations=(; SMILES=data.smiles))

                # Group table: symmetry-equivalent atoms are one group, counted by ν
                ν = [sum(model.groups.n_flattenedgroups[i][k] for i in eachindex(system))
                     for k in eachindex(data.groups)]
                @test (model.groups.flattenedgroups, ν) == (data.groups, data.ν)

                @test all(isapprox.([model.params.R.values; model.params.Q.values],
